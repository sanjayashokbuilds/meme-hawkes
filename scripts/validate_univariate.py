"""Parameter-recovery study: can our estimator find parameters we chose ourselves?

For each scenario: simulate many fake trade histories with known mu, alpha, beta,
fit each one, and compare the estimates with the truth. The scenarios match the
sizes of our real tokens (hundreds to about a thousand trades).

Usage (from the repo root): python scripts/validate_univariate.py
Writes figures/recovery.png, figures/qq_simulated.png and docs/VALIDATION.md.
"""

import sys

import matplotlib.pyplot as plt
import numpy as np

sys.path.insert(0, ".")
from meme_hawkes import hawkes  # noqa: E402
from meme_hawkes.plots import qq_plot, recovery_panel  # noqa: E402

SCENARIOS = [  # name, mu, alpha, beta, T   (expected events = mu * T / (1 - n))
    ("moderate excitation, ~1,000 events", 0.6, 0.8, 2.0, 1000),
    ("strong excitation, ~1,000 events", 0.2, 1.6, 2.0, 1000),
    ("strong excitation, ~300 events", 0.2, 1.6, 2.0, 300),
]
REPS = 100
rng = np.random.default_rng(2026)

rows, results = [], {}
for name, mu, alpha, beta, T in SCENARIOS:
    fits = []
    for _ in range(REPS):
        times = hawkes.simulate(mu, alpha, beta, T, rng)
        fits.append(hawkes.fit(times, T))
    est = {k: np.array([f[k] for f in fits]) for k in ("mu", "alpha", "beta", "n", "n_events")}
    results[name] = (est, {"mu": mu, "alpha": alpha, "beta": beta, "n": alpha / beta})
    for p, truth in [("mu", mu), ("beta", beta), ("n", alpha / beta)]:
        rows.append(f"| {name} | {p} | {truth:.2f} | {est[p].mean():.3f} | {est[p].mean() - truth:+.3f} "
                    f"| {est[p].std():.3f} |")
    print(f"done: {name} (mean events {est['n_events'].mean():.0f})")

# Figure 1: branching-ratio estimates per scenario
fig, axes = plt.subplots(1, 3, figsize=(12, 3.4), sharey=True)
for ax, (name, (est, truth)) in zip(axes, results.items()):
    recovery_panel(ax, est["n"], truth["n"], name)
    ax.set_xlabel("Estimated branching ratio n")
fig.tight_layout()
fig.savefig("figures/recovery.png", dpi=160)

# Figure 2: time-rescaling QQ plot for one simulated history, with the fitted model
times = hawkes.simulate(0.2, 1.6, 2.0, 1000, rng)
params = hawkes.fit(times, 1000)
fig, ax = plt.subplots(figsize=(4.2, 4))
qq_plot(ax, hawkes.rescaled_gaps(times, params["mu"], params["alpha"], params["beta"]),
        f"Simulated data, fitted model (KS p = {hawkes.goodness_of_fit(times, params):.2f})")
fig.tight_layout()
fig.savefig("figures/qq_simulated.png", dpi=160)

with open("docs/VALIDATION.md", "w") as f:
    f.write("# Validation on simulated data\n\n"
            f"Generated by `scripts/validate_univariate.py` ({REPS} simulations per scenario, seed 2026).\n"
            "Each row: the true value, the average estimate, the bias (average minus truth) "
            "and the spread (standard deviation across simulations).\n\n"
            "| Scenario | Parameter | True | Mean estimate | Bias | Spread |\n|---|---|---|---|---|---|\n")
    f.write("\n".join(rows) + "\n\n![Recovery of the branching ratio](../figures/recovery.png)\n\n"
            "![Time-rescaling QQ plot](../figures/qq_simulated.png)\n")
print("Wrote docs/VALIDATION.md and figures.")
