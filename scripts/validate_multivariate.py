"""Recovery study for the two-type model at the sizes of our real tokens.

Type 0 = early-wallet trades (few), type 1 = ordinary trades (most).
Two scenarios, each simulated many times and fitted:
  * "effect": each early trade triggers on average 0.5 ordinary trades
  * "null":   early trades trigger nothing; any estimated effect is noise
The null scenario shows how big an estimate can get by chance, so a real
result has to beat that to mean anything.

Usage (from the repo root): python scripts/validate_multivariate.py
Writes figures/recovery_multivariate.png and docs/VALIDATION_MULTIVARIATE.md.
"""

import sys

import matplotlib.pyplot as plt
import numpy as np

sys.path.insert(0, ".")
from meme_hawkes import multivariate as mv  # noqa: E402
from meme_hawkes.plots import recovery_panel  # noqa: E402

BETA, T, REPS = 1.0, 1500, 60
SCENARIOS = {  # alpha[i, j]: jump in type i after a type-j event (with beta = 1, alpha = branching)
    "effect (true early→ordinary = 0.5)": np.array([[0.3, 0.0], [0.5, 0.5]]),
    "null (true early→ordinary = 0)": np.array([[0.3, 0.0], [0.0, 0.5]]),
}
MU = np.array([0.02, 0.08])
rng = np.random.default_rng(2026)

rows, panels = [], []
for name, alpha in SCENARIOS.items():
    est, sizes = [], []
    for _ in range(REPS):
        times, types = mv.simulate(MU, alpha, BETA, T, rng)
        est.append(mv.fit(times, types, T)["branching"][1, 0])
        sizes.append(np.bincount(types, minlength=2))
    est, sizes = np.array(est), np.array(sizes)
    truth = alpha[1, 0] / BETA
    panels.append((name, est, truth))
    rows.append(f"| {name} | {sizes[:, 0].mean():.0f} | {sizes[:, 1].mean():.0f} | {truth:.2f} | "
                f"{est.mean():.3f} | {est.std():.3f} | {np.quantile(est, 0.95):.3f} |")
    print(f"done: {name}")

fig, axes = plt.subplots(1, 2, figsize=(10, 3.4), sharey=True)
for ax, (name, est, truth) in zip(axes, panels):
    recovery_panel(ax, est, truth, name)
    ax.set_xlabel("Estimated early→ordinary branching")
fig.tight_layout()
fig.savefig("figures/recovery_multivariate.png", dpi=160)

with open("docs/VALIDATION_MULTIVARIATE.md", "w") as f:
    f.write("# Validation of the two-type model\n\n"
            f"Generated by `scripts/validate_multivariate.py` ({REPS} simulations per scenario, seed 2026), "
            "at token-like sizes: a few dozen early-wallet trades and a few hundred ordinary ones.\n\n"
            "| Scenario | Early trades (avg) | Ordinary trades (avg) | True | Mean estimate | Spread | 95th percentile |\n"
            "|---|---|---|---|---|---|---|\n" + "\n".join(rows) +
            "\n\nThe null row's 95th percentile is the bar a single token's estimate must clear "
            "before we read it as more than noise.\n\n![Recovery](../figures/recovery_multivariate.png)\n")
print("Wrote docs/VALIDATION_MULTIVARIATE.md")
