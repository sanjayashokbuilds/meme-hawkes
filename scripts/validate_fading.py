"""Does a fading launch burst fool the constant-background model? (Simulation.)

Simulate token-like histories with a launch burst that fades plus moderate
self-excitation (true n = 0.4), then fit both models. If the constant model's
n comes out much higher, a high n on real tokens could be the same artefact.

Usage (from the repo root): python scripts/validate_fading.py
Writes figures/fading_validation.png and docs/VALIDATION_FADING.md.
"""

import sys

import matplotlib.pyplot as plt
import numpy as np

sys.path.insert(0, ".")
from meme_hawkes import fading, hawkes  # noqa: E402
from meme_hawkes.plots import recovery_panel  # noqa: E402

MU0, MU1, GAMMA, ALPHA, BETA, T, REPS = 0.05, 3.0, 0.01, 0.8, 2.0, 3000, 60
rng = np.random.default_rng(2026)

const_n, fade_n, const_ok, fade_ok, sizes = [], [], [], [], []
for _ in range(REPS):
    times = fading.simulate(MU0, MU1, GAMMA, ALPHA, BETA, T, rng)
    c, f = hawkes.fit(times, T), fading.fit(times, T)
    const_n.append(c["n"]); fade_n.append(f["n"]); sizes.append(len(times))
    const_ok.append(hawkes.goodness_of_fit(times, c) > 0.05)
    fade_ok.append(fading.goodness_of_fit(times, f) > 0.05)

fig, axes = plt.subplots(1, 2, figsize=(10, 3.4), sharey=True)
recovery_panel(axes[0], np.array(const_n), ALPHA / BETA, "Constant-background model")
recovery_panel(axes[1], np.array(fade_n), ALPHA / BETA, "Fading-background model")
for ax in axes:
    ax.set_xlabel("Estimated branching ratio n")
fig.tight_layout()
fig.savefig("figures/fading_validation.png", dpi=160)

with open("docs/VALIDATION_FADING.md", "w") as f:
    f.write("# Validation: launch burst vs self-excitation\n\n"
            f"Generated by `scripts/validate_fading.py` ({REPS} simulations, seed 2026). Each history has a launch burst "
            f"fading with half-life {np.log(2) / GAMMA:.0f} s on top of self-excitation with **true n = {ALPHA / BETA:.1f}**, "
            f"about {np.mean(sizes):.0f} events each.\n\n"
            "| Model | Mean estimated n | Spread | Passes fit check |\n|---|---|---|---|\n"
            f"| Constant background (Stages 3–4) | {np.mean(const_n):.3f} | {np.std(const_n):.3f} | {np.mean(const_ok):.0%} |\n"
            f"| Fading background (Stage 5b) | {np.mean(fade_n):.3f} | {np.std(fade_n):.3f} | {np.mean(fade_ok):.0%} |\n\n"
            "![Constant vs fading background](../figures/fading_validation.png)\n")
print(f"constant: n = {np.mean(const_n):.3f}, fit ok {np.mean(const_ok):.0%} | "
      f"fading: n = {np.mean(fade_n):.3f}, fit ok {np.mean(fade_ok):.0%}")
